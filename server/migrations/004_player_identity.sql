-- Player identity layer (Phase A — schema only, no behavior change).
-- A surrogate internal id becomes the canonical "this is one real person" key, decoupled
-- from any single source's numbering. player_source_ref is a crosswalk: one row per
-- (internal_id, source) with a confidence score, so a match the scoring module isn't sure
-- about can be served from today's existing heuristics (status auto_low) instead of being
-- silently trusted, while still getting queued for a human to confirm or reject in
-- player_match_candidates. Nothing reads or writes these tables yet — IDENTITY_MODE=off
-- until Phase B/C wire the scrapers to consult the resolver.
--
-- v1 scope is big-5 fd.org squads only; ESPN leagues and TM-supplemented (id=0) players
-- come in a later phase. The id range and source enum already have room reserved for them
-- so no schema change will be needed when that phase lands.

CREATE TYPE identity_source AS ENUM (
  'fdorg', 'sofascore', 'transfermarkt', 'thesportsdb', 'fpl', 'wikipedia', 'worldfootball', 'espn'
);

CREATE TYPE ref_status AS ENUM (
  'auto_high', 'auto_low', 'manual_confirmed', 'manual_rejected'
);

CREATE TYPE candidate_status AS ENUM (
  'pending', 'promoted', 'rejected', 'superseded'
);

-- Surrogate id starts at 10,000,000 — fd.org person ids are ~5 digits, ESPN athlete ids
-- are ~6 digits, so this range can never collide with either and a simple
-- "id < 10,000,000 → legacy fd.org id" rule works everywhere the client still uses one.
CREATE TABLE IF NOT EXISTS player_identity (
  id            bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 10000000) PRIMARY KEY,
  display_name  text        NOT NULL,
  dob           date,
  nationality   text,
  position      text,
  primary_source identity_source NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS player_source_ref (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  internal_id   bigint      NOT NULL REFERENCES player_identity(id) ON DELETE CASCADE,
  source        identity_source NOT NULL,
  external_id   text,
  external_slug text,
  external_name text,
  confidence    numeric(4,3) NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
  status        ref_status  NOT NULL,
  matched_by    text,                 -- which rule/strategy produced this ref, for audit
  evidence      jsonb,
  resolved_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source, external_id)
);

-- A rejected ref must not block a different candidate from becoming the active ref for the
-- same (internal_id, source) — only one *non-rejected* ref per (internal_id, source).
CREATE UNIQUE INDEX IF NOT EXISTS player_source_ref_active_unique
  ON player_source_ref (internal_id, source)
  WHERE status <> 'manual_rejected';

CREATE INDEX IF NOT EXISTS player_source_ref_internal_id ON player_source_ref (internal_id);

CREATE TABLE IF NOT EXISTS player_match_candidates (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  internal_id    bigint      NOT NULL REFERENCES player_identity(id) ON DELETE CASCADE,
  source         identity_source NOT NULL,
  external_id    text,
  external_slug  text,
  candidate_name text        NOT NULL,
  confidence     numeric(4,3) NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
  evidence       jsonb,
  status         candidate_status NOT NULL DEFAULT 'pending',
  created_at     timestamptz NOT NULL DEFAULT now(),
  decided_at     timestamptz,
  decided_by     text,
  UNIQUE (internal_id, source, external_id)
);

CREATE INDEX IF NOT EXISTS player_match_candidates_queue
  ON player_match_candidates (status, source, confidence DESC);

-- Compatibility columns: nullable so every existing row is unaffected until backfilled.
-- fd.org id stays each table's primary key — this is purely additive.
ALTER TABLE players         ADD COLUMN IF NOT EXISTS internal_id bigint REFERENCES player_identity(id);
ALTER TABLE player_profiles ADD COLUMN IF NOT EXISTS internal_id bigint REFERENCES player_identity(id);
ALTER TABLE player_seasons  ADD COLUMN IF NOT EXISTS internal_id bigint REFERENCES player_identity(id);
ALTER TABLE player_photos   ADD COLUMN IF NOT EXISTS internal_id bigint REFERENCES player_identity(id);

-- Service-role only, matching db/supabase.ts's access pattern for every other table here.
ALTER TABLE player_identity         ENABLE ROW LEVEL SECURITY;
ALTER TABLE player_source_ref       ENABLE ROW LEVEL SECURITY;
ALTER TABLE player_match_candidates ENABLE ROW LEVEL SECURITY;
